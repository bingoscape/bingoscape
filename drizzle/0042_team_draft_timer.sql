-- undo. Expand phase only, compatible with the previous app version (rolling
-- the app image back is safe; the database is not reverted):
--   * new nullable / defaulted columns (`draft.paused_remaining_ms`,
--     `draft_team_slot.consecutive_timeouts`, `draft_pick.undone_at`),
--   * a new table (`draft_queue_entry`), nothing existing is dropped,
--   * the two unique indexes of `draft_pick` become partial (they ignore undone
--     picks). The previous app hard-deletes on undo and never sets `undone_at`,
--     so for it the partial indexes behave exactly like the full ones.
--
-- Generated by drizzle-kit, then edited by hand: IF NOT EXISTS on the columns,
-- the CHECK constraints (drizzle-kit 0.24 does not emit them) and the index
-- swap kept together, so re-running the file is a no-op. Plain CREATE INDEX
-- (not CONCURRENTLY): drizzle runs a migration inside one transaction, and the
-- draft tables are tiny.

