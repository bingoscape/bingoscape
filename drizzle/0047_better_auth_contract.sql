-- Better Auth 4b (epic #250, issue #260): contract phase.
--
-- DO NOT DEPLOY until release 4a (#254, which stopped using all of this) has
-- run for at least one release with no rollback (see
-- docs/DATABASE-MIGRATION.md, "Better Auth 4b rollout"). Phase 3 (#253) went
-- live on 2026-10-26. This migration removes what only the NextAuth app used:
--   * the tables account, session and verification_token,
--   * the user columns password, session_revoked_at and email_verified (the
--     old timestamp; is_email_verified stays).
-- Rolling the app back to 4a still works; to 3/4 or older it does not (their
-- Drizzle schema still names the dropped user columns).
--
-- Generated by drizzle-kit, then written defensively by hand. Every step is
-- idempotent (a second run is a no-op) and re-checks its precondition. Before
-- account and users.password are dropped, whatever is still missing from
-- auth_account is copied (the same INSERTs as migration 0046); a drop whose
-- data is still not all in auth_account afterwards is skipped with a NOTICE,
-- so no password and no OAuth link is ever lost.

-- ---------------------------------------------------------------------------
-- 1. account: every NextAuth OAuth account must have its auth_account row
--    (same provider and provider account id). Missing ones are copied first
--    (0046's copy; NextAuth's `expires_at` is in seconds), then the table is
--    dropped only when none is missing.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  copied bigint;
  missing bigint;
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.tables
    WHERE table_schema = current_schema() AND table_name = 'bingoscape-next_account'
  ) THEN
    EXECUTE $q$
      INSERT INTO "bingoscape-next_auth_account"
        ("user_id", "provider_id", "account_id", "access_token", "refresh_token", "id_token", "access_token_expires_at", "scope")
      SELECT "user_id", "provider", "provider_account_id", "access_token", "refresh_token", "id_token",
        to_timestamp("expires_at"), "scope"
      FROM "bingoscape-next_account"
      ON CONFLICT ("provider_id", "account_id") DO NOTHING
    $q$;
    GET DIAGNOSTICS copied = ROW_COUNT;
    IF copied > 0 THEN
      RAISE NOTICE 'Better Auth 4b: copied % OAuth account(s) into auth_account', copied;
    END IF;
    EXECUTE $q$
      SELECT count(*) FROM "bingoscape-next_account" a
      WHERE NOT EXISTS (
        SELECT 1 FROM "bingoscape-next_auth_account" n
        WHERE n."provider_id" = a."provider" AND n."account_id" = a."provider_account_id"
      )
    $q$ INTO missing;
    IF missing > 0 THEN
      RAISE NOTICE 'Better Auth 4b: % account row(s) have no auth_account row; table account kept', missing;
    ELSE
      DROP TABLE "bingoscape-next_account";
    END IF;
  END IF;
END $$;--> statement-breakpoint

-- ---------------------------------------------------------------------------
-- 2. users.password: every user with a password must have a "credential"
--    auth_account row that holds a password. Missing ones are copied first
--    (0046's copy: account id = user id), then the column is dropped only
--    when none is missing. A credential row without a password is never
--    overwritten; such a user keeps the column (and the NOTICE says so).
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  copied bigint;
  missing bigint;
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema()
      AND table_name = 'bingoscape-next_user'
      AND column_name = 'password'
  ) THEN
    EXECUTE $q$
      INSERT INTO "bingoscape-next_auth_account" ("user_id", "provider_id", "account_id", "password")
      SELECT "id", 'credential', "id"::text, "password"
      FROM "bingoscape-next_user"
      WHERE "password" IS NOT NULL
      ON CONFLICT ("provider_id", "account_id") DO NOTHING
    $q$;
    GET DIAGNOSTICS copied = ROW_COUNT;
    IF copied > 0 THEN
      RAISE NOTICE 'Better Auth 4b: copied % password(s) into auth_account', copied;
    END IF;
    EXECUTE $q$
      SELECT count(*) FROM "bingoscape-next_user" u
      WHERE u."password" IS NOT NULL
        AND NOT EXISTS (
          SELECT 1 FROM "bingoscape-next_auth_account" n
          WHERE n."user_id" = u."id" AND n."provider_id" = 'credential' AND n."password" IS NOT NULL
        )
    $q$ INTO missing;
    IF missing > 0 THEN
      RAISE NOTICE 'Better Auth 4b: % password(s) have no credential account; column user.password kept', missing;
    ELSE
      ALTER TABLE "bingoscape-next_user" DROP COLUMN "password";
    END IF;
  END IF;
END $$;--> statement-breakpoint

-- ---------------------------------------------------------------------------
-- 3. Nothing to keep: NextAuth's session table only holds rows of an earlier
--    database-session setup (all expired; NextAuth used JWTs), and
--    verification_token was never written. Better Auth has its own
--    auth_session / auth_verification.
-- ---------------------------------------------------------------------------
DROP TABLE IF EXISTS "bingoscape-next_session";--> statement-breakpoint
DROP TABLE IF EXISTS "bingoscape-next_verification_token";--> statement-breakpoint

-- ---------------------------------------------------------------------------
-- 4. User columns only NextAuth read: session_revoked_at (JWT revocation;
--    Better Auth deletes session rows instead) and the email_verified
--    timestamp (it defaulted to CURRENT_TIMESTAMP and said nothing; Better
--    Auth uses is_email_verified, super admins provider_verified_email).
-- ---------------------------------------------------------------------------
ALTER TABLE "bingoscape-next_user" DROP COLUMN IF EXISTS "session_revoked_at";--> statement-breakpoint
ALTER TABLE "bingoscape-next_user" DROP COLUMN IF EXISTS "email_verified";
